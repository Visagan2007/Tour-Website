"""Regenerate lossless web-font subsets after changing icons, titles, or fonts.

Optional development tool: install `fonttools[woff]` to run this script.
The generated assets are used directly; normal Vite builds need only Node.js.
"""

from pathlib import Path
import re
import shutil

from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/Assets/fonts"
OUTPUT.mkdir(parents=True, exist_ok=True)


def check_glyphs(source, result, characters):
    """Verify identical visible outlines, advances, and baseline metrics."""
    original = TTFont(source)
    optimized = TTFont(result)
    for table, fields in {
        "head": ("unitsPerEm",),
        "hhea": ("ascent", "descent", "lineGap"),
        "OS/2": (
            "sTypoAscender", "sTypoDescender", "sTypoLineGap",
            "usWinAscent", "usWinDescent",
        ),
    }.items():
        for field in fields:
            assert getattr(original[table], field) == getattr(optimized[table], field), (source, field)

    locations = [{}]
    if "fvar" in original:
        axis = next(axis for axis in original["fvar"].axes if axis.axisTag == "wght")
        locations = [{"wght": weight} for weight in (axis.minValue, axis.defaultValue, axis.maxValue, 500, 600)]

    for location in locations:
        before = original.getGlyphSet(location=location)
        after = optimized.getGlyphSet(location=location)
        for point in set(characters):
            before_name = original.getBestCmap()[point]
            after_name = optimized.getBestCmap()[point]
            before_pen = DecomposingRecordingPen(before)
            after_pen = DecomposingRecordingPen(after)
            before[before_name].draw(before_pen)
            after[after_name].draw(after_pen)
            assert before_pen.value == after_pen.value, (source, point, location, "outline")
            assert before[before_name].width == after[after_name].width, (source, point, location, "advance")
    original.close()
    optimized.close()


def make_subset(source, output, characters):
    options = subset.Options()
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.notdef_outline = True
    options.recalc_bounds = False
    options.recalc_timestamp = False
    font = TTFont(source, recalcBBoxes=False, recalcTimestamp=False)
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=characters)
    subsetter.subset(font)
    # Dancing Script reserves its primary name; rename only the derived font's
    # internal names. Its CSS alias and rendered glyphs stay unchanged.
    if output.name == "dancing-script-logo.woff2":
        for record in font["name"].names:
            if record.nameID in {1, 4, 16, 21}:
                record.string = "Thendral Logo Script".encode(record.getEncoding())
            elif record.nameID in {3, 6, 25}:
                record.string = "ThendralLogoScript".encode(record.getEncoding())
    font.flavor = "woff2"
    font.save(output)
    font.close()
    check_glyphs(source, output, characters)
    print(f"{output.name}: {source.stat().st_size:,} -> {output.stat().st_size:,} bytes; glyphs verified")


# Keep upstream Bootstrap geometry and the exact original CSS codepoints.
bootstrap = ROOT / "node_modules/bootstrap-icons"
upstream_css = (bootstrap / "font/bootstrap-icons.css").read_text(encoding="utf-8")
used_icons = set()
for component in (ROOT / "src").rglob("*.jsx"):
    used_icons.update(re.findall(r"\bbi-[a-z0-9-]+", component.read_text(encoding="utf-8")))
icon_rules = {}
for name, point in re.findall(r'\.(bi-[a-z0-9-]+)::before\s*\{\s*content:\s*"\\([a-f0-9]+)";\s*\}', upstream_css):
    if name in used_icons:
        icon_rules[name] = int(point, 16)
assert set(icon_rules) == used_icons, "A used icon is missing from the installed Bootstrap font"
make_subset(bootstrap / "font/fonts/bootstrap-icons.woff2", OUTPUT / "bootstrap-icons.woff2", set(icon_rules.values()))
base_styles = upstream_css[upstream_css.index(".bi::before,"):upstream_css.index(".bi-123::before")].strip()
license_header = upstream_css[:upstream_css.index("@font-face")].strip()
icon_css = license_header + '''

/* Generated by scripts/optimize-fonts.py; preserve the original icon rendering. */
@font-face {
  font-display: block;
  font-family: "bootstrap-icons";
  src: url("./Assets/fonts/bootstrap-icons.woff2") format("woff2");
}

''' + base_styles + "\n\n"
icon_css += "\n".join(f'.{name}::before {{ content: "\\{point:x}"; }}' for name, point in sorted(icon_rules.items())) + "\n"
(ROOT / "src/icons.css").write_text(icon_css, encoding="utf-8")
shutil.copyfile(bootstrap / "LICENSE", OUTPUT / "bootstrap-icons-LICENSE.txt")


# Subset fixed display text only; body and input fonts retain their repertoire.
nav_source = (ROOT / "src/Components/NavBar/NavBar.jsx").read_text(encoding="utf-8")
word_markup = re.search(r'className="word">(.*?)</div>', nav_source, re.S).group(1)
logo_text = re.sub(r"<[^>]+>", "", word_markup)
about_source = (ROOT / "src/Components/AboutUs/AboutUs.jsx").read_text(encoding="utf-8")
about_titles = re.findall(r'<h[12]\b[^>]*className="section-title reveal"[^>]*>([^<]+)</h[12]>', about_source)
assert about_titles, "Could not find the original display headings"
jobs = [
    ("@fontsource/poppins", "poppins-devanagari-700-normal.woff2", "poppins-rupee-700.woff2", {0x20B9}, "poppins-LICENSE.txt"),
    ("@fontsource/pacifico", "pacifico-latin-400-normal.woff2", "pacifico-logo.woff2", set(map(ord, logo_text)), "pacifico-LICENSE.txt"),
    ("@fontsource-variable/dancing-script", "dancing-script-latin-wght-normal.woff2", "dancing-script-logo.woff2", set(map(ord, logo_text)), "dancing-script-LICENSE.txt"),
    ("@fontsource/rubik-dirt", "rubik-dirt-latin-400-normal.woff2", "rubik-dirt-headings.woff2", set(map(ord, " ".join(about_titles))), "rubik-dirt-LICENSE.txt"),
]
for package, filename, output, characters, license_name in jobs:
    package_root = ROOT / "node_modules" / package
    make_subset(package_root / "files" / filename, OUTPUT / output, characters)
    shutil.copyfile(package_root / "LICENSE", OUTPUT / license_name)
